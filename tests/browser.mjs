import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { createApp } from '../server/app.mjs';
import { openStore } from '../server/store.mjs';
import { mkdir } from 'node:fs/promises';
const store=openStore(':memory:');
const session=store.create('Browser QA','',true);
const server=createApp(store,{production:true,preview:true}).listen(3100,'127.0.0.1');
await new Promise(r=>server.once('listening',r));
const browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
const failures=[];
await mkdir('/workspace/work/qa',{recursive:true});
try {
 const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,deviceScaleFactor:1});
 await context.addInitScript(session=>localStorage.setItem('gather:last',JSON.stringify(session)),session);
 const page=await context.newPage();page.on('pageerror',e=>failures.push(e.message));
 await page.goto('http://127.0.0.1:3100');await page.getByRole('button',{name:'Customize floor plan'}).waitFor();
 const guest=store.state(session.id).guests.find(g=>!g.tableId);
 await page.locator('.mobile-pool-button').click();
 await page.getByRole('button',{name:`Select ${guest.name}`,exact:true}).click();
 const picker=page.getByRole('dialog',{name:`Seat ${guest.name}`,exact:true});await picker.waitFor();
 assert.ok(await picker.getByRole('button',{name:/Table 01.*chairs available/}).isVisible());
 await page.waitForTimeout(350);
 await page.screenshot({path:'/workspace/work/qa/mobile-picker.png'});
 await picker.getByRole('button',{name:/Table 01.*chairs available/}).click();
 await picker.waitFor({state:'hidden'});
 assert.equal(store.state(session.id).guests.find(g=>g.id===guest.id).tableId,store.state(session.id).tables[0].id);
 // Select another guest, exercise filtering and cancellation.
 await page.locator('.mobile-pool-button').click();
 const other=store.state(session.id).guests.find(g=>!g.tableId);
 await page.getByRole('button',{name:`Select ${other.name}`,exact:true}).click();
 const picker2=page.getByRole('dialog',{name:`Seat ${other.name}`,exact:true});
 await picker2.getByRole('searchbox').fill('no such table');await picker2.getByText('No matching tables.',{exact:false}).waitFor();
 await picker2.getByRole('button',{name:'Cancel',exact:true}).click();
 assert.equal(store.state(session.id).guests.find(g=>g.id===other.id).tableId,null);
 const seats=JSON.stringify(store.state(session.id).guests);
 await page.getByRole('button',{name:'Customize floor plan'}).click();
 const editor=page.getByRole('dialog',{name:'Customize floor plan',exact:true});await editor.waitFor();
 await editor.getByLabel('Select to edit').selectOption('stage');
 await editor.getByLabel('Label',{exact:true}).fill('Band stage');
 await editor.getByRole('spinbutton',{name:'Left',exact:true}).fill('240');
 await editor.getByRole('spinbutton',{name:'Width',exact:true}).fill('210');
 const image=await page.screenshot();
 await editor.locator('input[type=file]').setInputFiles({name:'venue.png',mimeType:'image/png',buffer:image});
 await editor.getByRole('button',{name:'Replace floor-plan image'}).waitFor();
 await editor.getByLabel('Image opacity').fill('0.4');
 await page.screenshot({path:'/workspace/work/qa/mobile-editor.png'});
 await editor.getByRole('button',{name:'Save floor plan',exact:true}).click();await editor.waitFor({state:'hidden'});
 assert.equal(JSON.stringify(store.state(session.id).guests),seats);
 assert.equal(store.state(session.id).floorPlan.elements[0].label,'Band stage');
 assert.equal(store.state(session.id).floorPlan.elements[0].x,240);
 assert.equal(store.state(session.id).floorPlan.image.opacity,.4);
 await page.reload();await page.getByRole('button',{name:'Customize floor plan'}).click();
 await editor.getByLabel('Select to edit').selectOption('stage');assert.equal(await editor.getByLabel('Label',{exact:true}).inputValue(),'Band stage');
 // Cancel must discard edits, including image removal.
 await editor.getByLabel('Label',{exact:true}).fill('Unsaved');await editor.getByLabel('Select to edit').selectOption('image');
 await editor.getByRole('button',{name:'Remove image',exact:true}).click();
 await editor.getByRole('button',{name:'Cancel',exact:true}).click();
 assert.ok(store.state(session.id).floorPlan.image);assert.equal(store.state(session.id).floorPlan.elements[0].label,'Band stage');
 await context.close();
 const desktop=await browser.newContext({viewport:{width:1440,height:1100}});
 await desktop.addInitScript(session=>localStorage.setItem('gather:last',JSON.stringify(session)),session);
 const pc=await desktop.newPage();pc.on('pageerror',e=>failures.push(e.message));await pc.goto('http://127.0.0.1:3100');
 await pc.getByRole('button',{name:'Customize floor plan'}).click();const ed=pc.getByRole('dialog',{name:'Customize floor plan',exact:true});
 await ed.getByLabel('Select to edit').selectOption('stage');
 const stage=ed.getByRole('button',{name:'Select Band stage',exact:true});const bounds=await stage.boundingBox();
 await pc.mouse.move(bounds.x+bounds.width/2,bounds.y+bounds.height/2);await pc.mouse.down();await pc.mouse.move(bounds.x+bounds.width/2+40,bounds.y+bounds.height/2+25,{steps:8});await pc.mouse.up();
 assert.ok(Number(await ed.getByRole('spinbutton',{name:'Left',exact:true}).inputValue())>240);
 const width=Number(await ed.getByRole('spinbutton',{name:'Width',exact:true}).inputValue());
 const handle=await ed.locator('.resize-handle').boundingBox();await pc.mouse.move(handle.x+handle.width/2,handle.y+handle.height/2);await pc.mouse.down();await pc.mouse.move(handle.x+handle.width/2+30,handle.y+handle.height/2+20,{steps:6});await pc.mouse.up();
 assert.ok(Number(await ed.getByRole('spinbutton',{name:'Width',exact:true}).inputValue())>width);
 await ed.getByLabel('Add venue element').selectOption('bar');
 await ed.getByLabel('Label',{exact:true}).fill('Cocktail bar');
 await pc.screenshot({path:'/workspace/work/qa/desktop-editor.png'});
 await ed.getByRole('button',{name:'Save floor plan',exact:true}).click();await ed.waitFor({state:'hidden'});
 assert.equal(store.state(session.id).floorPlan.elements.at(-1).label,'Cocktail bar');assert.equal(JSON.stringify(store.state(session.id).guests),seats);
 // A full table cannot be selected in the picker.
 const full=store.state(session.id).tables[0];store.updateTable(session.id,full.id,{name:full.name,capacity:7});
 await pc.reload();await pc.getByRole('button',{name:`Select ${other.name}`,exact:true}).click();
 const fullOption=pc.getByRole('dialog').getByRole('button',{name:/Table 01.*full/});assert.equal(await fullOption.isDisabled(),true);
 await desktop.close();assert.deepEqual(failures,[]);
 console.log('PASS: mobile picker, filtering, cancel, full tables, image upload, persistence, desktop drag/resize/add, and seating preservation.');
} finally {await browser.close();server.closeAllConnections();await new Promise(r=>server.close(r));store.db.close();}
